#!/usr/bin/env python3
"""Score the WRF runs added after the results were known (config post_hoc_runs) against their baseline.

    python scripts/scoring/post_hoc.py --runs-root RUNS

These runs are not part of the criteria H1-H5 and are not in results/scores.csv. For each post-hoc
run, the post-hoc run and its baseline are scored on the same 24 h windows (the post-hoc run's
score_start/score_ndays), on the same IMD cells, with the same metrics as score_all.py, both at
12 km (d01) and 3 km (d02). Then, for the cloudburst day (03 UTC 26 to 03 UTC 27 July 2005):
  - box mean and maximum on the IMD grid (as fig 5),
  - Santacruz: nearest grid point, largest value within 50 km, largest value on the whole grid
    (the domain maximum is what Litta et al. 2007 compared with the observations),
  - the ten gauges of config/stations_mumbai2005.yaml at their nearest grid points.

Writes data/daily_post_hoc/<run>/*.nc, results/post_hoc/<run>.csv, results/post_hoc/POST_HOC.md and
results/figures/story/fig12_post_hoc_daily.png. Runs whose output is missing are skipped.
"""
from __future__ import annotations

import argparse
import sys
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "postprocess"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import DATA, ROOT, load_config  # noqa: E402
import metrics as M  # noqa: E402
from extract_precip import target_grid, windows, wrf_daily  # noqa: E402
from remap import Remapper  # noqa: E402
from score_all import obs_for_event, score_run  # noqa: E402
import story_figures as SF  # noqa: E402

BURST = (datetime(2005, 7, 26, 3), datetime(2005, 7, 27, 3))
RES = {"d01": "12km", "d02": "3km"}


def daily_on_imd(files, wins, tla, tlo):
    daily, lat, lon, dx = wrf_daily(files, wins)
    rm = Remapper(lat, lon, tla, tlo, src_dx_km=dx)
    return np.stack([rm(d) for d in daily]), daily, lat, lon


def save(field, wins, tla, tlo, f):
    f.parent.mkdir(parents=True, exist_ok=True)
    xr.DataArray(field.astype("float32"), dims=("day", "lat", "lon"),
                 coords={"day": np.array([s for s, _ in wins], dtype="datetime64[s]"), "lat": tla, "lon": tlo},
                 name="pr", attrs={"units": "mm/day", "window": "24 h from the 'day' time (03 UTC)",
                                   "note": "post-hoc scoring, not part of H1-H5"}).to_netcdf(f)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs-root", type=Path, required=True)
    a = ap.parse_args()
    cfg = load_config()
    sc = cfg["scoring"]
    st = SF.load_stations()
    out_dir = ROOT / "results" / "post_hoc"
    out_dir.mkdir(parents=True, exist_ok=True)
    md = ["# Post-hoc runs (generated by scripts/scoring/post_hoc.py)", "",
          "Runs added after the nine runs had been scored. They are **not** part of the criteria H1-H5",
          "(docs/metrics.md) and are not in results/scores.csv. Each changes one setting of its baseline.", ""]
    fig_rows = []
    for name, p in SF.post_hoc_runs(cfg):
        ev = dict(cfg["events"][p["event"]], score_start=p["score_start"], score_ndays=p["score_ndays"])
        wins = windows(ev)
        tla, tlo = target_grid(ev)
        dirs = {"post-hoc": a.runs_root / "wrf" / name, "baseline": a.runs_root / "wrf" / p["baseline"]}
        if not all(any(d.glob("wrfout_d02_*")) for d in dirs.values()):
            print(f"{name}: output of the run or its baseline missing, skipped")
            continue
        rsl = dirs["post-hoc"] / "rsl.error.0000"
        done = (dirs["post-hoc"] / "timing.txt").exists() or \
            (rsl.exists() and b"SUCCESS COMPLETE WRF" in rsl.read_bytes()[-5000:])
        if not done:                                 # run_wrf.sh writes timing.txt when wrf.exe succeeds
            print(f"{name}: not finished (no timing.txt, no SUCCESS COMPLETE WRF), skipped")
            continue
        o, labels = obs_for_event(cfg, ev, tla, tlo)
        b = ev["score_box"]
        inbox = ((tla >= b["lat_min"]) & (tla <= b["lat_max"]))[:, None] & ((tlo >= b["lon_min"]) & (tlo <= b["lon_max"]))[None, :]
        mask = inbox & np.all(np.isfinite(o), axis=0)
        w = M.area_weights(tla, tlo)
        rows, burst, gauges = [], [], []
        kb = [k for k, (s, _) in enumerate(wins) if s == BURST[0]]
        for which, d in dirs.items():
            for dom, res in RES.items():
                field, native, la, lo = daily_on_imd(sorted(d.glob(f"wrfout_{dom}_*")), wins, tla, tlo)
                run = f"WRF_{res}_{p['driver']}_{which}"
                save(field, wins, tla, tlo, DATA / "daily_post_hoc" / name / f"{run}.nc")
                for k, v in score_run(field, o, mask, w, tla, tlo, sc["thresholds_mm_day"],
                                      sc["fss_window_points"]).items():
                    rows.append(dict(run=run, window=f"{labels[0]}..{labels[-1]}", metric=k, value=v))
                mean = [float(np.sum(np.where(mask, x, 0) * w) / np.sum(np.where(mask, w, 0))) for x in field]
                mx = [float(np.nanmax(np.where(mask, x, np.nan))) for x in field]
                fig_rows.append((name, which, res, labels, mean, mx))
                if kb:
                    k = kb[0]
                    nat = native[k]
                    j = SF.nearest(la, lo, SF.SANTACRUZ)
                    burst.append(dict(run=run, box_mean_imd=mean[k], box_max_imd=mx[k], santacruz_point=nat[j],
                                      santacruz_max_50km=float(nat[SF.within(la, lo, SF.SANTACRUZ, 50)].max()),
                                      grid_max=float(nat.max())))
                    if st is not None:
                        for g, (gla, glo, tot, _) in st["stations"].items():
                            gauges.append(dict(gauge=g, observed=tot, run=run, model=float(nat[SF.nearest(la, lo, (gla, glo))])))
        om = [float(np.sum(np.where(mask, x, 0) * w) / np.sum(np.where(mask, w, 0))) for x in o]
        ox = [float(np.nanmax(np.where(mask, x, np.nan))) for x in o]
        fig_rows.append((name, "IMD", None, labels, om, ox))
        df = pd.DataFrame(rows)
        df.to_csv(out_dir / f"{name}.csv", index=False, float_format="%.4f")
        md += [f"## {name}", "", p["why"].strip(), "",
               f"Baseline `{p['baseline']}` starts {cfg['events'][p['event']]['sim_start']}; this run starts "
               f"{p['sim_start']}. Scored on IMD days {labels[0]} to {labels[-1]} (24 h ending 08:30 IST), "
               f"both runs on the same windows and cells.", ""]
        if burst:
            bd = pd.DataFrame(burst).set_index("run")
            obs_k = kb[0]
            md += ["### Cloudburst day (24 h ending 08:30 IST 27 July 2005)", "",
                   f"Observed: IMD box mean {om[obs_k]:.0f} mm, box maximum {ox[obs_k]:.0f} mm; "
                   f"Santacruz gauge {SF.SANTACRUZ_MM:.0f} mm.", "",
                   "Model values in mm; `santacruz_*` and `grid_max` on the model grid (3 km or 12 km), "
                   "`box_*_imd` on the IMD grid.", "", bd.round(0).to_markdown(), ""]
        head = ["bias_pct", "corr_total", "peak_ratio", "maxloc_err_km", "FSS_64.5mm_5pt", "FSS_115.6mm_5pt",
                "FSS_204.5mm_5pt"]
        t = df.pivot(index="run", columns="metric", values="value")
        md += [f"### Scores over IMD days {labels[0]} to {labels[-1]}", "",
               "The same metrics as results/SCORECARD.md, but over these days only, so not comparable with it.", "",
               t[[c for c in head if c in t.columns]].round(2).to_markdown(), ""]
        if gauges:
            gd = pd.DataFrame(gauges).pivot(index=["gauge", "observed"], columns="run", values="model")
            md += ["### Gauges (24 h to 08:30 IST 27 July; nearest grid point; mm)", "",
                   "Gauge totals from Litta et al. (2007, Fig. 1), source IMD; positions in "
                   "config/stations_mumbai2005.yaml.", "", gd.round(0).to_markdown(), ""]
    if len(md) <= 5:
        sys.exit("no post-hoc run could be scored")
    (out_dir / "POST_HOC.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    figure(cfg, fig_rows)


def figure(cfg, fig_rows):
    plt = SF.plt
    names = sorted({r[0] for r in fig_rows})
    for name in names:
        rows = [r for r in fig_rows if r[0] == name]
        fig, axes = plt.subplots(1, 2, figsize=(9.0, 3.4), sharex=True)
        for ax, i, what in ((axes[0], 4, "box mean"), (axes[1], 5, "box maximum")):
            for _, which, res, labels, mean, mx in rows:
                x = [f"{lb:%d %b}" for lb in labels]
                v = mean if i == 4 else mx
                if which == "IMD":
                    ax.plot(x, v, color=SF.COL["IMD"], lw=2.4, marker="o", ms=4, label="IMD (observed)", zorder=5)
                else:
                    col = SF.COL["POSTHOC"] if which == "post-hoc" else SF.COL["WRF"]
                    ls = SF.LS["3km" if res == "3km" else "12km"]
                    p = cfg["post_hoc_runs"][name] if which == "post-hoc" else None
                    lab = (SF.post_hoc_label(p, res.replace("km", " km")) if p else
                           f"WRF {res.replace('km', ' km')}, start {datetime.fromisoformat(cfg['events'][cfg['post_hoc_runs'][name]['event']]['sim_start']):%d %b}")
                    ax.plot(x, v, color=col, ls=ls, lw=1.6, marker="o" if res == "3km" else None, ms=3, label=lab)
            ax.set_ylabel(f"{what} (mm/day)")
            ax.set_xlabel("IMD day (24 h ending 08:30 IST), July 2005")
            ax.grid(axis="y", color=SF.RULE, lw=0.5)
            ax.spines[["top", "right"]].set_visible(False)
            ax.set_ylim(bottom=0)
        axes[1].legend(fontsize=7, loc="upper left", bbox_to_anchor=(1.01, 1.0))
        fig.suptitle(f"Post-hoc run {name} and its baseline over the scoring box (not part of H1-H5)", fontsize=9)
        out = ROOT / "results" / "figures" / "story"
        out.mkdir(parents=True, exist_ok=True)
        fig.savefig(out / "fig12_post_hoc_daily.png", bbox_inches="tight")
        plt.close(fig)
        print("fig12 written")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate every WPS, WRF and RegCM5 namelist from config/experiment.yaml.

Run from the repository root:
    python scripts/generate_namelists.py

The namelists in namelists/ are committed, but they are always regenerated from
the YAML so that domains, dates and scoring regions cannot drift apart.
"""
from __future__ import annotations

import math
from datetime import datetime, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
R_EARTH_WRF = 6370000.0  # WRF/WPS spherical earth radius (m)


# ---------------------------------------------------------------- geometry ----
def merc_xy(lat, lon, truelat, lon0):
    """Mercator coordinates (m) on the WRF sphere, true at `truelat`."""
    k = R_EARTH_WRF * math.cos(math.radians(truelat))
    x = k * math.radians(lon - lon0)
    y = k * math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))
    return x, y


def merc_latlon(x, y, truelat, lon0):
    k = R_EARTH_WRF * math.cos(math.radians(truelat))
    lon = lon0 + math.degrees(x / k)
    lat = math.degrees(2 * math.atan(math.exp(y / k)) - math.pi / 2)
    return lat, lon


def nest_parent_start(outer, inner, center):
    """1-based parent (i, j) of the nest's lower-left corner so the nest is
    centred on `center`. WPS puts ref_lat/ref_lon at mass index (e_we/2, e_sn/2)
    and a nest with ratio r spans (e_we_nest-1)/r parent cells starting at the
    lower-left corner of parent cell i_parent_start."""
    dx = outer["dx_km"] * 1000.0
    x0, y0 = merc_xy(outer["center_lat"], outer["center_lon"], outer["truelat"], outer["center_lon"])
    xc, yc = merc_xy(center["lat"], center["lon"], outer["truelat"], outer["center_lon"])
    i_c = outer["nx"] / 2.0 + (xc - x0) / dx
    j_c = outer["ny"] / 2.0 + (yc - y0) / dx
    half_i = (inner["nx"] - 1) / inner["ratio"] / 2.0
    half_j = (inner["ny"] - 1) / inner["ratio"] / 2.0
    i_ps = int(round(i_c + 0.5 - half_i))
    j_ps = int(round(j_c + 0.5 - half_j))
    # actual centre achieved after rounding
    i_act = i_ps - 0.5 + half_i
    j_act = j_ps - 0.5 + half_j
    lat_act, lon_act = merc_latlon(x0 + (i_act - outer["nx"] / 2.0) * dx,
                                   y0 + (j_act - outer["ny"] / 2.0) * dx,
                                   outer["truelat"], outer["center_lon"])
    return i_ps, j_ps, lat_act, lon_act


def domain_corners(nx, ny, dx_km, clat, clon, truelat):
    dx = dx_km * 1000.0
    x0, y0 = merc_xy(clat, clon, truelat, clon)
    sw = merc_latlon(x0 - (nx - 1) / 2 * dx, y0 - (ny - 1) / 2 * dx, truelat, clon)
    ne = merc_latlon(x0 + (nx - 1) / 2 * dx, y0 + (ny - 1) / 2 * dx, truelat, clon)
    return sw, ne


# ------------------------------------------------------------------ helpers ----
def wrf_date(s):
    return datetime.fromisoformat(s)


def fmt_nml(groups):
    """Write Fortran namelist groups from an ordered list of (name, [(key, value)])."""
    out = []
    for gname, items in groups:
        out.append(f" &{gname}")
        for k, v in items:
            out.append(f" {k:<32} = {v},")
        out.append(" /")
        out.append("")
    return "\n".join(out)


def q(s):
    return f"'{s}'"


def two(a, b):
    return f"{a}, {b}"


# ---------------------------------------------------------------- WPS / WRF ----
def wps_namelist(cfg, ev_name, ev, driver):
    o, n = cfg["outer_domain"], cfg["inner_domain"]
    s, e = wrf_date(ev["sim_start"]), wrf_date(ev["sim_end"])
    ips, jps, _, _ = nest_parent_start(o, n, ev["inner_center"])
    prefix = "TWCR" if driver == "20CRv3" else "ERA5"
    sd = s.strftime("%Y-%m-%d_%H:%M:%S")
    ed = e.strftime("%Y-%m-%d_%H:%M:%S")
    groups = [
        ("share", [
            ("wrf_core", q("ARW")), ("max_dom", 2),
            ("start_date", f"{q(sd)}, {q(sd)}"), ("end_date", f"{q(ed)}, {q(ed)}"),
            ("interval_seconds", 3 * 3600), ("io_form_geogrid", 2),
        ]),
        ("geogrid", [
            ("parent_id", two(1, 1)), ("parent_grid_ratio", two(1, n["ratio"])),
            ("i_parent_start", two(1, ips)), ("j_parent_start", two(1, jps)),
            ("e_we", two(o["nx"], n["nx"])), ("e_sn", two(o["ny"], n["ny"])),
            ("geog_data_res", f"{q('default')}, {q('default')}"),
            ("dx", int(o["dx_km"] * 1000)), ("dy", int(o["dx_km"] * 1000)),
            ("map_proj", q("mercator")),
            ("ref_lat", o["center_lat"]), ("ref_lon", o["center_lon"]),
            ("truelat1", o["truelat"]), ("stand_lon", o["center_lon"]),
            ("geog_data_path", q("WPS_GEOG_PATH")),
        ]),
        ("ungrib", [("out_format", q("WPS")), ("prefix", q(prefix))]),
        ("metgrid", [("fg_name", q(prefix)), ("io_form_metgrid", 2)]),
    ]
    head = (f"! WPS namelist  event={ev_name}  driver={driver}\n"
            f"! Generated by scripts/generate_namelists.py from config/experiment.yaml. Do not edit.\n"
            f"! WPS_GEOG_PATH is replaced by scripts/run/run_wps.sh.\n")
    if driver == "20CRv3":
        head += "! 20CRv3 intermediate files are written directly by scripts/preprocess/twcr_to_wps.py (no ungrib).\n"
    else:
        head += "! ERA5 GRIB from CDS is ungribbed with Vtable.ECMWF.\n"
    return head + fmt_nml(groups)


def wrf_namelist(cfg, ev_name, ev, driver):
    o, n = cfg["outer_domain"], cfg["inner_domain"]
    s, e = wrf_date(ev["sim_start"]), wrf_date(ev["sim_end"])
    ips, jps, _, _ = nest_parent_start(o, n, ev["inner_center"])
    run_h = int((e - s).total_seconds() // 3600)

    def pair(a, b=None):
        return two(a, a if b is None else b)

    groups = [
        ("time_control", [
            ("run_days", 0), ("run_hours", run_h), ("run_minutes", 0), ("run_seconds", 0),
            ("start_year", pair(s.year)), ("start_month", pair(f"{s.month:02d}")),
            ("start_day", pair(f"{s.day:02d}")), ("start_hour", pair(f"{s.hour:02d}")),
            ("end_year", pair(e.year)), ("end_month", pair(f"{e.month:02d}")),
            ("end_day", pair(f"{e.day:02d}")), ("end_hour", pair(f"{e.hour:02d}")),
            ("interval_seconds", 3 * 3600),
            ("input_from_file", ".true., .true."),
            ("history_interval", two(60, 60)),
            ("frames_per_outfile", two(1000, 1000)),
            ("restart", ".false."), ("restart_interval", 100000),
            ("io_form_history", 2), ("io_form_restart", 2),
            ("io_form_input", 2), ("io_form_boundary", 2),
            ("iofields_filename", f"{q('iofields.txt')}, {q('iofields.txt')}"),
            ("ignore_iofields_warning", ".true."),
            ("debug_level", 0),
        ]),
        ("domains", [
            ("time_step", int(5 * o["dx_km"])),       # 60 s at 12 km (5*dx rule)
            ("time_step_fract_num", 0), ("time_step_fract_den", 1),
            ("max_dom", 2),
            ("e_we", two(o["nx"], n["nx"])), ("e_sn", two(o["ny"], n["ny"])),
            ("e_vert", two(o["vertical_levels_wrf"], o["vertical_levels_wrf"])),
            ("p_top_requested", int(o["ptop_hpa"] * 100)),
            ("num_metgrid_levels", "NUM_METGRID_LEVELS"),
            ("num_metgrid_soil_levels", 4),
            ("dx", two(int(o["dx_km"] * 1000), int(n["dx_km"] * 1000))),
            ("dy", two(int(o["dx_km"] * 1000), int(n["dx_km"] * 1000))),
            ("grid_id", two(1, 2)), ("parent_id", two(0, 1)),
            ("i_parent_start", two(1, ips)), ("j_parent_start", two(1, jps)),
            ("parent_grid_ratio", two(1, n["ratio"])),
            ("parent_time_step_ratio", two(1, n["ratio"])),
            ("feedback", 0),          # one-way: the 12 km field is an independent 12 km result
            ("smooth_option", 0),
        ]),
        ("physics", [
            ("mp_physics", two(8, 8)),            # Thompson
            ("ra_lw_physics", two(4, 4)),         # RRTMG
            ("ra_sw_physics", two(4, 4)),
            ("radt", two(12, 12)),
            ("sf_sfclay_physics", two(1, 1)),     # revised MM5
            ("sf_surface_physics", two(2, 2)),    # Noah: same 4-layer LSM as 20CRv3
            ("bl_pbl_physics", two(1, 1)),        # YSU
            ("bldt", two(0, 0)),
            ("cu_physics", two(3, 0)),            # Grell-Freitas (scale-aware) at 12 km, explicit at 3 km
            ("cudt", two(0, 0)),
            ("isfflx", 1), ("ifsnow", 1), ("icloud", 1),
            ("surface_input_source", 3),
            ("num_soil_layers", 4),
            ("num_land_cat", 21),
            ("sf_urban_physics", two(0, 0)),
            ("sst_update", 0),
            ("aer_opt", 0),                       # no climatological aerosol (same in RegCM5)
        ]),
        ("fdda", [("grid_fdda", two(0, 0))]),     # no interior nudging in either model
        ("dynamics", [
            ("hybrid_opt", 2), ("etac", 0.2),
            ("w_damping", 1),
            ("diff_opt", two(1, 1)), ("km_opt", two(4, 4)),
            ("diff_6th_opt", two(0, 0)),
            ("base_temp", 290.0),
            ("damp_opt", 3), ("zdamp", two(5000.0, 5000.0)), ("dampcoef", two(0.2, 0.2)),
            ("khdif", two(0, 0)), ("kvdif", two(0, 0)),
            ("non_hydrostatic", ".true., .true."),
            ("moist_adv_opt", two(1, 1)), ("scalar_adv_opt", two(1, 1)),
            ("gwd_opt", two(0, 0)),                 # no orographic GWD (RegCM5 has none either)
        ]),
        ("bdy_control", [
            ("spec_bdy_width", 5), ("specified", ".true., .false."),
            ("nested", ".false., .true."),
        ]),
    ]
    head = (f"! WRF namelist  event={ev_name}  driver={driver}\n"
            f"! Generated by scripts/generate_namelists.py from config/experiment.yaml. Do not edit.\n"
            f"! NUM_METGRID_LEVELS is filled from the met_em files by scripts/run/run_wrf.sh.\n")
    return head + fmt_nml(groups)


IOFIELDS = """-:h:0:QCLOUD,QRAIN,QICE,QSNOW,QGRAUP,QNICE,QNRAIN,QNWFA,QNIFA,REFL_10CM
"""


# -------------------------------------------------------------------- RegCM ----
def regcm_namelist(cfg, ev_name, ev, driver, res):
    """res = '12km' (driven by 20CRv3/ERA5) or '03km' (FNEST from the 12 km run)."""
    o, n = cfg["outer_domain"], cfg["inner_domain"]
    s, e = wrf_date(ev["sim_start"]), wrf_date(ev["sim_end"])
    d = lambda t: f"{t.year:04d}{t.month:02d}{t.day:02d}{t.hour:02d}"
    tag = f"{ev_name}_{driver}"
    if res == "12km":
        # dot-point dims are one more than cross points; 271x241 cross matches WRF d01
        jx, iy, kz, ds = o["nx"] + 1, o["ny"] + 1, o["vertical_levels_regcm"], o["dx_km"]
        clat, clon = o["center_lat"], o["center_lon"]
        dattyp = ssttyp = "ERA5"
        dt, nsp = 90, 20
        cup = 5                 # Tiedtke, as in the RegCM5 CORDEX 12 km setup
        inpglob = f"DRIVER_DIR/{driver}"
        fnest = None
        domname = f"{tag}_12km"
        atmfrq = 3.0
    else:
        _, _, clat, clon = nest_parent_start(o, n, ev["inner_center"])
        jx, iy, kz, ds = n["nx"] + 1, n["ny"] + 1, n["vertical_levels_regcm"], n["dx_km"]
        dattyp = ssttyp = "FNEST"
        dt, nsp = 30, 31
        cup = 0                 # explicit convection, as in RegCM5 EUR-03
        inpglob = "RCMDATA"
        fnest = (f"RUN_ROOT/regcm/{tag}_12km/output", f"{tag}_12km")
        domname = f"{tag}_03km"
        atmfrq = 3.0
    groups = [
        ("dimparam", [("iy", iy), ("jx", jx), ("kz", kz)]),
        ("coreparam", [("idynamic", 3)]),          # MOLOCH non-hydrostatic core
        ("geoparam", [("iproj", q("NORMER")), ("ds", ds), ("ptop", o["ptop_hpa"] / 10.0),
                      ("clat", round(clat, 4)), ("clon", round(clon, 4))]),
        ("terrainparam", [("domname", q(domname)), ("h2opct", 50.0), ("h2ohgt", ".false."),
                          ("dirter", q("input")), ("inpter", q("RCMDATA"))]),
        ("boundaryparam", [("nspgx", nsp), ("nspgd", nsp), ("high_nudge", 6.0),
                           ("medium_nudge", 4.0), ("low_nudge", 2.0)]),
        ("globdatparam", [("ibdyfrq", 3), ("ssttyp", q(ssttyp)), ("dattyp", q(dattyp)),
                          ("gdate1", d(s)), ("gdate2", d(e)), ("calendar", q("gregorian")),
                          ("dirglob", q("input")), ("inpglob", q(inpglob))]),
    ]
    if fnest:
        groups.append(("fnestparam", [("coarse_outdir", q(fnest[0])), ("coarse_domname", q(fnest[1]))]))
    groups += [
        ("restartparam", [("ifrest", ".false."), ("mdate0", d(s)), ("mdate1", d(s)), ("mdate2", d(e))]),
        ("timeparam", [("dt", float(dt))]),
        ("outparam", [("ifsave", ".false."), ("ifatm", ".true."), ("atmfrq", atmfrq),
                      ("ifrad", ".false."), ("ifsrf", ".true."), ("srffrq", 1.0),
                      ("ifsts", ".true."), ("ifshf", ".true."), ("ifsub", ".false."),
                      ("iflak", ".false."), ("ifchem", ".false."), ("outnwf", 0.0),
                      ("dirout", q("output"))]),
        ("physicsparam", [("iboudy", 5), ("ibltyp", 1), ("icup_lnd", cup), ("icup_ocn", cup),
                          ("ipptls", 2), ("iocnflx", 2), ("iocnrough", 1), ("iocnzoq", 1),
                          ("scenario", q("SSP245")), ("idcsst", 0), ("iseaice", 0),
                          ("iconvlwp", 0), ("icldfrac", 1 if cup else 0), ("irrtm", 0),
                          ("iclimao3", 1), ("isolconst", 0), ("iclimaaer", 0)]),
        ("cldparam", [("ncld", 0)]),
    ]
    head = (f"! RegCM5 namelist  event={ev_name}  driver={driver}  resolution={res}\n"
            f"! Generated by scripts/generate_namelists.py from config/experiment.yaml. Do not edit.\n"
            f"! Physics follow the RegCM5 CORDEX namelists shipped with the model\n"
            f"! (Testing/CORDEX/EUR-12_RegCM5_ERA5 and EUR-03_RegCM5_ERA5), adapted for nesting.\n"
            f"! DRIVER_DIR and RUN_ROOT are replaced by scripts/run/run_regcm.sh.\n")
    if res == "12km":
        head += (f"! dattyp/ssttyp 'ERA5' is the RegCM ERA5 netCDF reader; for driver={driver} the\n"
                 f"! files under DRIVER_DIR/{driver}/ERA5/ are written by the scripts in scripts/preprocess.\n")
    return head + fmt_nml(groups)


# --------------------------------------------------------------------- main ----
def main():
    cfg = yaml.safe_load((ROOT / "config/experiment.yaml").read_text())
    o, n = cfg["outer_domain"], cfg["inner_domain"]
    out = ROOT / "namelists"
    report = ["# Generated domain geometry", ""]
    sw, ne = domain_corners(o["nx"], o["ny"], o["dx_km"], o["center_lat"], o["center_lon"], o["truelat"])
    report.append(f"Outer 12 km domain: SW corner {sw[0]:.2f}N {sw[1]:.2f}E, NE corner {ne[0]:.2f}N {ne[1]:.2f}E")
    for ev_name, ev in cfg["events"].items():
        ips, jps, lat_c, lon_c = nest_parent_start(o, n, ev["inner_center"])
        sw, ne = domain_corners(n["nx"], n["ny"], n["dx_km"], lat_c, lon_c, o["truelat"])
        report.append(f"{ev_name}: WRF d02 i_parent_start={ips} j_parent_start={jps}, centre {lat_c:.3f}N {lon_c:.3f}E, "
                      f"SW {sw[0]:.2f}N {sw[1]:.2f}E, NE {ne[0]:.2f}N {ne[1]:.2f}E")
        for drv in ev["drivers"]:
            (out / "wps" / f"namelist.wps.{ev_name}_{drv}").write_text(wps_namelist(cfg, ev_name, ev, drv))
            (out / "wrf" / f"namelist.input.{ev_name}_{drv}").write_text(wrf_namelist(cfg, ev_name, ev, drv))
            for res in ("12km", "03km"):
                (out / "regcm" / f"{ev_name}_{drv}_{res}.in").write_text(
                    regcm_namelist(cfg, ev_name, ev, drv, res))
    (out / "wrf" / "iofields.txt").write_text(IOFIELDS)
    (out / "GEOMETRY.md").write_text("\n".join(report) + "\n")
    print("\n".join(report))


if __name__ == "__main__":
    main()
